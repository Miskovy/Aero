import { Injectable, Logger } from '@nestjs/common';
import { DockerService } from '../docker/docker.service';
import {
  CloudflareError,
  CloudflareResponse,
  CloudflareDnsSearchResponse,
  DockerNetworkSettings
} from './interfaces/cloudflare.interface'

@Injectable()
export class CloudflareService {
  private readonly logger = new Logger(CloudflareService.name);
  private readonly apiToken = process.env.CLOUDFLARE_API_TOKEN;
  private readonly zoneId = process.env.CLOUDFLARE_ZONE_ID;
  private readonly tunnelId = process.env.CLOUDFLARE_TUNNEL_ID;
  private readonly accountId = process.env.CLOUDFLARE_ACCOUNT_ID;

  constructor(private readonly dockerService: DockerService) { }

  async createDeploymentDomain(subdomain: string) {
    if (!this.apiToken || !this.zoneId) {
      this.logger.warn(
        'Cloudflare credentials missing. Skipping DNS generation.',
      );
      return false;
    }

    const targetUrl = this.tunnelId
      ? `${this.tunnelId}.cfargotunnel.com`
      : undefined;

    if (!targetUrl) {
      this.logger.warn(
        'CLOUDFLARE_TUNNEL_ID is missing. Need a routing target.',
      );
      return false;
    }

    try {
      const response = await fetch(
        `https://api.cloudflare.com/client/v4/zones/${this.zoneId}/dns_records`,
        {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${this.apiToken}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            type: 'CNAME',
            name: subdomain,
            content: targetUrl,
            proxied: true,
            comment: 'Auto-generated by Aero MVP',
            ttl: 1,
          }),
        },
      );

      const data = (await response.json()) as CloudflareResponse;

      if (!data.success) {
        if (
          data.errors &&
          data.errors.some((e: CloudflareError) => e.code === 81053)
        ) {
          this.logger.log(`CNAME record for ${subdomain} already exists.`);
          return true;
        }
        this.logger.error(
          `Cloudflare API Error: ${JSON.stringify(data.errors)}`,
        );
        return false;
      }

      this.logger.log(`Created CNAME record for ${subdomain} -> ${targetUrl}`);
      return true;
    } catch (error) {
      this.logger.error(
        `Failed to register Cloudflare domain for ${subdomain}`,
        error,
      );
      return false;
    }
  }

  /**
   * Updates the Cloudflare tunnel's ingress rules to route traffic to
   * the correct Docker containers. Call this after deploying/removing services.
   */
  async updateTunnelIngress(
    services: {
      slug: string;
      domain: string;
      containerId: string;
      port: number;
    }[],
  ): Promise<boolean> {
    if (!this.apiToken || !this.accountId || !this.tunnelId) {
      this.logger.warn(
        'Cloudflare account/tunnel config missing. Cannot update ingress.',
      );
      return false;
    }

    try {
      // Build ingress rules from running services
      const ingressRules: any[] = [];

      for (const svc of services) {
        // Get the container's Docker bridge IP address
        let originUrl = `http://localhost:${svc.port}`;
        try {
          const info = await this.dockerService.inspectContainer(
            svc.containerId,
          );
          const networkSettings = info.NetworkSettings as unknown as
            | DockerNetworkSettings
            | undefined;
          let containerIp = networkSettings?.IPAddress;

          if (!containerIp && networkSettings?.Networks) {
            const firstNetwork = Object.values(networkSettings.Networks)[0];
            containerIp = firstNetwork?.IPAddress;
          }

          if (containerIp) {
            originUrl = `http://${containerIp}:${svc.port}`;
          }
        } catch {
          this.logger.warn(
            `Could not inspect container for ${svc.slug}, using localhost`,
          );
        }

        ingressRules.push({
          hostname: svc.domain,
          service: originUrl,
        });
      }

      // Cloudflare requires a catch-all rule at the end
      ingressRules.push({
        service: 'http_status:404',
      });

      // Update tunnel configuration via Cloudflare API
      const response = await fetch(
        `https://api.cloudflare.com/client/v4/accounts/${this.accountId}/cfd_tunnel/${this.tunnelId}/configurations`,
        {
          method: 'PUT',
          headers: {
            Authorization: `Bearer ${this.apiToken}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            config: {
              ingress: ingressRules,
            },
          }),
        },
      );

      const result = (await response.json()) as CloudflareResponse;
      if (result.success) {
        this.logger.log(
          `Tunnel ingress updated with ${ingressRules.length - 1} service(s)`,
        );
        return true;
      } else {
        this.logger.error(
          `Failed to update tunnel ingress: ${JSON.stringify(result.errors)}`,
        );
        return false;
      }
    } catch (error) {
      this.logger.error('Failed to update tunnel ingress', error);
      return false;
    }
  }

  async deleteDeploymentDomain(subdomain: string) {
    if (!this.apiToken || !this.zoneId) return false;
    try {
      const searchRes = await fetch(
        `https://api.cloudflare.com/client/v4/zones/${this.zoneId}/dns_records?name=${subdomain}`,
        {
          headers: { Authorization: `Bearer ${this.apiToken}` },
        },
      );
      const searchData =
        (await searchRes.json()) as CloudflareDnsSearchResponse;
      const record = searchData.result?.[0];

      if (!record) return true;

      const deleteRes = await fetch(
        `https://api.cloudflare.com/client/v4/zones/${this.zoneId}/dns_records/${record.id}`,
        {
          method: 'DELETE',
          headers: { Authorization: `Bearer ${this.apiToken}` },
        },
      );
      const deleteData = (await deleteRes.json()) as CloudflareResponse;
      if (deleteData.success) {
        this.logger.log(`Deleted DNS record for ${subdomain}`);
        return true;
      }
      return false;
    } catch (e) {
      this.logger.error(`Failed to delete DNS for ${subdomain}`, e);
      return false;
    }
  }
}
