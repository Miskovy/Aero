import { Command } from 'commander';
import { AeroAgent } from '../agent/agent.js';
import { apiClient } from '../api/api.js';
import chalk from 'chalk';

export function createDaemonCommand() {
  const daemonCmd = new Command('daemon')
    .description('Manage the Aero Agent background daemon for this server');

  daemonCmd
    .command('start')
    .description('Start the Aero Agent to connect to the Control Plane')
    .requiredOption('-t, --token <token>', 'The agent pairing token generated by the Control Plane')
    .option('--api <url>', 'The URL of the Aero Control Plane API', apiClient.defaults.baseURL || 'https://aero-y6mm.onrender.com')
    .action((options) => {
      console.log(chalk.bold.blue('\nAero Agent Initialization'));
      console.log(chalk.gray('-------------------------'));
      
      const agent = new AeroAgent(options.token, options.api);
      agent.start();

      // Keep the process alive and handle graceful shutdown
      process.on('SIGINT', () => {
        agent.stop();
        process.exit(0);
      });
      process.on('SIGTERM', () => {
        agent.stop();
        process.exit(0);
      });
    });

  daemonCmd
    .command('status')
    .description('Check the local Aero Agent environment and dependencies')
    .action(async () => {
      console.log(chalk.bold('Aero Agent Status\n'));
      
      try {
        const { execSync } = await import('node:child_process');
        execSync('docker info', { stdio: 'ignore' });
        console.log(chalk.green('✓ Docker is running and accessible'));
      } catch {
        console.log(chalk.red('✗ Docker is NOT running or accessible. The agent requires Docker.'));
      }

      console.log(chalk.gray('\nNote: The Aero Agent currently runs in the foreground via `aero daemon start`.'));
      console.log(chalk.gray('Background service management (systemd/launchd) will be added in a future update.'));
    });

  return daemonCmd;
}
